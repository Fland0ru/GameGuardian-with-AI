package android.ext.ai;

/* The AI assistant: an embedded Lua script that runs on the real GameGuardian script engine.
   All memory operations go through the native gg.* API with correct threading.
   The Java side provides gg.aiRequest (HTTP), gg.aiWait (waits for user input),
   gg.aiShow / gg.aiLog (transcript updates). */
public final class AiScriptSource {

    private AiScriptSource() {
    }

    public static final java.lang.String LUA = "local TYPES = {byte = gg.TYPE_BYTE, word = gg.TYPE_WORD, dword = gg.TYPE_DWORD, qword = gg.TYPE_QWORD, float = gg.TYPE_FLOAT, double = gg.TYPE_DOUBLE}\n"
            + "local messages = {}\n"
            + "local function typ(s)\n"
            + "  local t = TYPES[s]\n"
            + "  if t == nil then return gg.TYPE_DWORD end\n"
            + "  return t\n"
            + "end\n"
            + "local function parse_addr(a)\n"
            + "  if type(a) == 'number' then return a end\n"
            + "  a = tostring(a or ''):gsub('^0[xX]', '')\n"
            + "  return tonumber(a, 16)\n"
            + "end\n"
            + "local function dispatch(name, a)\n"
            + "  a = a or {}\n"
            + "  if name == 'search_number' then\n"
            + "    local ok = gg.searchNumber(tostring(a.value or ''), typ(a.data_type))\n"
            + "    if type(ok) == 'string' then return {error = ok} end\n"
            + "    return {count = gg.getResultsCount()}\n"
            + "  elseif name == 'refine_number' then\n"
            + "    if gg.getResultsCount() == 0 then return {error = 'no current results; call search_number first'} end\n"
            + "    local ok = gg.refineNumber(tostring(a.value or ''), typ(a.data_type))\n"
            + "    if type(ok) == 'string' then return {error = ok} end\n"
            + "    return {count = gg.getResultsCount()}\n"
            + "  elseif name == 'get_results' then\n"
            + "    local n = a.count or 20\n"
            + "    if n < 1 then n = 1 end\n"
            + "    if n > 100 then n = 100 end\n"
            + "    local rows = gg.getResults(n)\n"
            + "    if type(rows) ~= 'table' then return {error = tostring(rows)} end\n"
            + "    local out = {}\n"
            + "    for i = 1, #rows do\n"
            + "      out[i] = {address = string.format('0x%X', rows[i].address), value = tostring(rows[i].value), flags = rows[i].flags}\n"
            + "    end\n"
            + "    return {results = out, total = gg.getResultsCount()}\n"
            + "  elseif name == 'read_values' then\n"
            + "    local items = {}\n"
            + "    local src = a.addresses or {}\n"
            + "    for i = 1, #src do\n"
            + "      items[i] = {address = parse_addr(src[i].address), flags = typ(src[i].data_type)}\n"
            + "    end\n"
            + "    local vals = gg.getValues(items)\n"
            + "    if type(vals) ~= 'table' then return {error = tostring(vals)} end\n"
            + "    local out = {}\n"
            + "    for i = 1, #vals do\n"
            + "      out[i] = {address = string.format('0x%X', vals[i].address), value = tostring(vals[i].value)}\n"
            + "    end\n"
            + "    return {values = out}\n"
            + "  elseif name == 'write_values' then\n"
            + "    local ok = gg.setValues({{address = parse_addr(a.address), value = tostring(a.value or ''), flags = typ(a.data_type)}})\n"
            + "    if type(ok) == 'string' then return {error = ok} end\n"
            + "    return {ok = true}\n"
            + "  elseif name == 'freeze_values' then\n"
            + "    local addr = parse_addr(a.address)\n"
            + "    local fl = typ(a.data_type)\n"
            + "    local ok = gg.setValues({{address = addr, value = tostring(a.value or ''), flags = fl}})\n"
            + "    if type(ok) == 'string' then return {error = ok} end\n"
            + "    local ok2 = gg.addListItems({{address = addr, value = tostring(a.value or ''), flags = fl, name = 'AI', freeze = true, freezeType = gg.FREEZE_NORMAL}})\n"
            + "    if type(ok2) == 'string' then return {error = ok2} end\n"
            + "    return {ok = true, frozen = true}\n"
            + "  elseif name == 'clear_results' then\n"
            + "    gg.clearResults()\n"
            + "    return {ok = true}\n"
            + "  elseif name == 'get_target_info' then\n"
            + "    local info = gg.getTargetInfo()\n"
            + "    if info == nil then return {attached = false} end\n"
            + "    return {attached = true, name = info.name, packageName = info.packageName, pid = info.pid, x64 = info.x64}\n"
            + "  end\n"
            + "  return {error = 'unknown tool ' .. tostring(name)}\n"
            + "end\n"
            + "local function trim_history()\n"
            + "  while #messages > 60 do\n"
            + "    if messages[2] ~= nil and messages[2].role == 'user' then\n"
            + "      table.remove(messages, 2)\n"
            + "    else\n"
            + "      break\n"
            + "    end\n"
            + "  end\n"
            + "end\n"
            + "table.insert(messages, {role = 'system', content = [[You are an AI assistant embedded in a game memory editor (GameGuardian) on Android. You help the user find and modify values in the attached game process by calling the provided tools. Guide the user: ask for the current visible value (coins, HP, etc.), search for it, ask them to change it in game if too many results remain, refine, then write or freeze. Keep answers short and reply in the language the user writes in.]]})\n"
            + "while true do\n"
            + "  local user = gg.aiWaitUser()\n"
            + "  if user == nil or user == '' then break end\n"
            + "  table.insert(messages, {role = 'user', content = user})\n"
            + "  local final = nil\n"
            + "  for round = 1, 12 do\n"
            + "    local resp = gg.aiRequest(messages)\n"
            + "    if type(resp) == 'string' then\n"
            + "      final = '[error] ' .. resp\n"
            + "      break\n"
            + "    end\n"
            + "    local calls = resp.tool_calls\n"
            + "    if calls == nil or #calls == 0 then\n"
            + "      final = tostring(resp.content or '')\n"
            + "      table.insert(messages, {role = 'assistant', content = final})\n"
            + "      trim_history()\n"
            + "      break\n"
            + "    end\n"
            + "    local m = {role = 'assistant', tool_calls = calls}\n"
            + "    if resp.content ~= nil and resp.content ~= '' then\n"
            + "      m.content = tostring(resp.content)\n"
            + "    end\n"
            + "    table.insert(messages, m)\n"
            + "    for i = 1, #calls do\n"
            + "      local call = calls[i]\n"
            + "      local fn = call['function'] or {}\n"
            + "      gg.aiShow('[tool] ' .. tostring(fn.name))\n"
            + "      local ok, result = pcall(dispatch, fn.name, fn.arguments or {})\n"
            + "      if not ok then\n"
            + "        result = {error = tostring(result)}\n"
            + "      end\n"
            + "      table.insert(messages, {role = 'tool', tool_call_id = call.id or fn.name, content = result})\n"
            + "    end\n"
            + "  end\n"
            + "  if final == nil then final = 'Tool-call round limit reached.' end\n"
            + "  gg.aiShow(final)\n"
            + "end\n";
}
